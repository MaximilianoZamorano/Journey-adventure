
CREATE TABLE users (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR2(120) NOT NULL,
    email VARCHAR2(150) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    role VARCHAR2(20) DEFAULT 'client' NOT NULL
);


CREATE TABLE destinations (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(120) NOT NULL,
    country VARCHAR2(80) NOT NULL,
    description CLOB,
    is_active NUMBER(1) DEFAULT 1 NOT NULL
);


CREATE TABLE packages (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR2(120) NOT NULL,
    description CLOB,
    base_price NUMBER(10, 2) NOT NULL,
    min_stops NUMBER DEFAULT 2 NOT NULL
);

CREATE TABLE package_stops (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id NUMBER NOT NULL,
    destination_id NUMBER NOT NULL,
    stop_order NUMBER NOT NULL,
    CONSTRAINT fk_ps_package FOREIGN KEY (package_id) REFERENCES packages(id),
    CONSTRAINT fk_ps_destination FOREIGN KEY (destination_id) REFERENCES destinations(id),
    CONSTRAINT uq_package_order UNIQUE (package_id, stop_order)
);


CREATE TABLE departures (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id NUMBER NOT NULL,
    departure_date DATE NOT NULL,
    return_date DATE NOT NULL,
    unit_price NUMBER(10, 2) NOT NULL,
    total_slots NUMBER NOT NULL,
    available_slots NUMBER NOT NULL,
    status VARCHAR2(20) DEFAULT 'open' NOT NULL,
    CONSTRAINT fk_dep_package FOREIGN KEY (package_id) REFERENCES packages(id)
);


CREATE TABLE reservations (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER NOT NULL,
    departure_id NUMBER NOT NULL,
    reservation_date TIMESTAMP NOT NULL,
    passenger_count NUMBER NOT NULL,
    contracted_price NUMBER(10, 2) NOT NULL,
    status VARCHAR2(20) DEFAULT 'confirmed' NOT NULL,
    CONSTRAINT fk_res_user FOREIGN KEY (user_id) REFERENCES users(id),
    CONSTRAINT fk_res_departure FOREIGN KEY (departure_id) REFERENCES departures(id)
);


CREATE TABLE passengers (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id NUMBER NOT NULL,
    full_name VARCHAR2(120) NOT NULL,
    document_id VARCHAR2(40) NOT NULL,
    CONSTRAINT fk_pas_reservation FOREIGN KEY (reservation_id) REFERENCES reservations(id)
);

CREATE TABLE trip_progress (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id NUMBER NOT NULL,
    stop_id NUMBER NOT NULL,
    stage_status VARCHAR2(20) DEFAULT 'pending' NOT NULL,
    updated_at TIMESTAMP NOT NULL,
    updated_by_user_id NUMBER NULL,
    CONSTRAINT fk_tp_reservation FOREIGN KEY (reservation_id) REFERENCES reservations(id),
    CONSTRAINT fk_tp_stop FOREIGN KEY (stop_id) REFERENCES package_stops(id),
    CONSTRAINT fk_tp_user FOREIGN KEY (updated_by_user_id) REFERENCES users(id)
);
